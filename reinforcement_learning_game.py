import numpy as np
import random

# Initialize Q-learning table
Q = {}

# Game settings
WIN_REWARD = 1
LOSE_REWARD = -1
DRAW_REWARD = 0.2

LEARNING_RATE = 0.1
DISCOUNT = 0.9
EPSILON = 0.2


# Create empty board
def create_board():
    return [0] * 9


# Display board
def display_board(board):
    symbols = {0: " ", 1: "X", -1: "O"}

    for i in range(0, 9, 3):
        print(" | ".join(symbols[x] for x in board[i:i+3]))
        if i < 6:
            print("---------")


# Check winner
def check_winner(board, player):

    winning_positions = [
        (0, 1, 2), (3, 4, 5),
        (6, 7, 8), (0, 3, 6),
        (1, 4, 7), (2, 5, 8),
        (0, 4, 8), (2, 4, 6)
    ]

    for a, b, c in winning_positions:
        if board[a] == board[b] == board[c] == player:
            return True

    return False


# Get available moves
def available_moves(board):
    return [i for i in range(9) if board[i] == 0]


# Get Q values for a state
def get_q(state):

    if state not in Q:
        Q[state] = np.zeros(9)

    return Q[state]


# AI chooses an action
def choose_action(board, training=False):

    state = tuple(board)
    moves = available_moves(board)

    if training and random.random() < EPSILON:
        return random.choice(moves)

    q_values = get_q(state)

    best_moves = [
        move for move in moves
        if q_values[move] == max(q_values[m] for m in moves)
    ]

    return random.choice(best_moves)


# Train AI using Q-learning
def train_ai(episodes=50000):

    global Q

    print("Training AI...")

    for episode in range(episodes):

        board = create_board()

        while True:

            # AI plays X
            state = tuple(board)
            action = choose_action(board, training=True)

            board[action] = 1

            # Check AI win
            if check_winner(board, 1):
                reward = WIN_REWARD
                next_state = None

            elif not available_moves(board):
                reward = DRAW_REWARD
                next_state = None

            else:

                # Opponent plays randomly
                opponent_move = random.choice(
                    available_moves(board)
                )

                board[opponent_move] = -1

                # Check opponent win
                if check_winner(board, -1):
                    reward = LOSE_REWARD
                    next_state = None

                elif not available_moves(board):
                    reward = DRAW_REWARD
                    next_state = None

                else:
                    reward = 0
                    next_state = tuple(board)

            # Q-learning update
            old_value = get_q(state)[action]

            if next_state is None:
                future_value = 0
            else:
                future_value = max(
                    get_q(next_state)[m]
                    for m in available_moves(list(next_state))
                )

            new_value = old_value + LEARNING_RATE * (
                reward + DISCOUNT * future_value - old_value
            )

            get_q(state)[action] = new_value

            if next_state is None:
                break

    print("AI Training Completed!")


# Play against AI
def play_game():

    board = create_board()

    print("\nYou are O")
    print("AI is X")
    print("Positions are numbered 0 to 8:\n")

    print("0 | 1 | 2")
    print("---------")
    print("3 | 4 | 5")
    print("---------")
    print("6 | 7 | 8")

    while True:

        # AI turn
        ai_move = choose_action(board)

        board[ai_move] = 1

        print("\nAI played:")
        display_board(board)

        if check_winner(board, 1):
            print("AI Wins!")
            break

        if not available_moves(board):
            print("Game Draw!")
            break

        # Human turn
        while True:

            try:
                human_move = int(input("\nEnter your move (0-8): "))

                if human_move in available_moves(board):
                    break

                print("Invalid position! Try again.")

            except ValueError:
                print("Please enter a valid number.")

        board[human_move] = -1

        display_board(board)

        if check_winner(board, -1):
            print("Congratulations! You Win!")
            break

        if not available_moves(board):
            print("Game Draw!")
            break


# Main program
if __name__ == "__main__":

    train_ai()

    while True:

        play_game()

        again = input("\nPlay again? (yes/no): ")

        if again.lower() != "yes":
            print("Thank you for playing!")
            break